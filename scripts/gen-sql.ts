// Generates the Supabase migration from the app's own log definitions, so the server
// schema can never drift from the client.   node scripts/gen-sql.ts > supabase/migrations/…sql
import { LOGS, SITE_SCOPE, type FieldType } from '../src/engine/schema.ts';

const q = (s: string) => `"${s}"`;
const pgType = (t: FieldType) =>
  t === 'datetime' ? 'timestamp' : t === 'date' || t === 'month' ? 'date' : t === 'number' || t === 'money' || t === 'percent' || t === 'score' ? 'double precision' : 'text';

const out: string[] = [];
const sql = (s: string) => out.push(s.trim() + '\n');

sql(`
-- =====================================================================
-- BenchMark – central database (Supabase / PostgreSQL 15+)
-- GENERATED by scripts/gen-sql.ts – do not edit by hand.
-- Idempotent: after every BenchMark upgrade, run the latest version of this file again.
--
-- Roles (profiles.role):
--   admin      Project Controls: everything, users, sites, targets, period lock
--   executive  MD, CEO, COO, group managers: read every site, write nothing
--   pm         read the sites they are a member of; write only the projects
--              where projects.pm = their owner_name (and those projects' records)
--   pending    signed in but not yet approved by an admin: no access
-- Rows are never hard-deleted (deleted = true), every write bumps rev, and
-- server_updated_at drives incremental sync. All writes go through bm_push().
-- =====================================================================

create extension if not exists pgcrypto;

-- ---------- users, sites, membership ----------
create table if not exists sites (
  code text primary key,
  name text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  full_name text,
  owner_name text,           -- the name used in the logs, e.g. 'A. Camara'
  role text not null default 'pending' check (role in ('pending', 'pm', 'executive', 'admin')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists site_members (
  user_id uuid not null references profiles (id) on delete cascade,
  site_code text not null references sites (code) on update cascade,
  primary key (user_id, site_code)
);

-- every new auth user (password invite or Microsoft sign-in) gets a 'pending' profile
create or replace function bm_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, email, full_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name'))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists bm_on_auth_user on auth.users;
create trigger bm_on_auth_user after insert on auth.users for each row execute function bm_new_user();

-- ---------- permission helpers (security definer: no RLS recursion) ----------
create or replace function bm_role() returns text language sql stable security definer set search_path = public as $$
  select coalesce((select role from profiles where id = auth.uid() and active), 'none')
$$;
create or replace function bm_owner() returns text language sql stable security definer set search_path = public as $$
  select owner_name from profiles where id = auth.uid() and active
$$;
create or replace function bm_member(site text) returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from site_members where user_id = auth.uid() and site_code = site)
$$;
create or replace function bm_can_read(site text) returns boolean language sql stable as $$
  select case bm_role()
    when 'admin' then true
    when 'executive' then true
    when 'pm' then site is null or bm_member(site)
    else false end
$$;

-- ---------- org-wide settings & KPI targets (admin writes, everyone reads) ----------
create table if not exists org_settings (
  id text primary key,
  data jsonb not null,
  deleted boolean not null default false,
  updated_at timestamptz,
  rev bigint not null default 0,
  site_id text,
  updated_by uuid,
  server_updated_at timestamptz not null default now()
);
create table if not exists kpi_targets (like org_settings including all);

-- ---------- audit trail (append-only) ----------
create table if not exists audit (
  id text primary key,                -- device id + local sequence
  ts timestamptz not null,
  user_id uuid not null default auth.uid(),
  user_name text,
  log text,
  row_id text,
  action text not null,
  summary text,
  before jsonb,
  after jsonb,
  received_at timestamptz not null default now()
);
`);

for (const def of LOGS) {
  const cols = def.fields.map((f) => `  ${q(f.key)} ${pgType(f.type)}`).join(',\n');
  sql(`
-- ---------- ${def.key} ----------
create table if not exists ${q(def.key)} (
  id text primary key,
${cols},
  deleted boolean not null default false,
  updated_at timestamptz,
  rev bigint not null default 0,
  site_id text references sites (code) on update cascade,
  updated_by uuid,
  server_updated_at timestamptz not null default now()
);
-- upgrades: columns added in later versions (re-running this file is safe)
${def.fields.map((f) => `alter table ${q(def.key)} add column if not exists ${q(f.key)} ${pgType(f.type)};`).join('\n')}
create index if not exists ${q(def.key + '_sync')} on ${q(def.key)} (server_updated_at, id);
create index if not exists ${q(def.key + '_site')} on ${q(def.key)} (site_id);`);
}

sql(`
-- ---------- project helpers (need the projects table) ----------
create or replace function bm_project_site(p text) returns text language sql stable security definer set search_path = public as $$
  select site from "projects" where code = p and not deleted
$$;
create or replace function bm_owns_project(p text) returns boolean language sql stable security definer set search_path = public as $$
  select bm_role() = 'pm' and exists (
    select 1 from "projects" where code = p and not deleted and pm = bm_owner() and bm_member(site))
$$;

-- ---------- triggers ----------
-- 1. derive site_id (the permission anchor) from the project or the row's own site
create or replace function bm_set_site() returns trigger language plpgsql as $$
declare scope text := tg_argv[0]; j jsonb := to_jsonb(new);
begin
  if scope = 'self' then new.site_id := j ->> 'site';
  elsif scope = 'project' then new.site_id := bm_project_site(j ->> 'project');
  elsif scope = 'site' then new.site_id := j ->> 'site';
  elsif scope = 'projectOrSite' then new.site_id := coalesce(bm_project_site(j ->> 'project'), j ->> 'site');
  else new.site_id := null;
  end if;
  if scope <> 'global' and new.site_id is null then
    raise exception 'BM_NO_SITE: record has no site (set the project''s site, or the record''s site)' using errcode = 'P0001';
  end if;
  return new;
end $$;

-- 2. period lock: nobody but an admin writes into a locked month
create or replace function bm_check_lock() returns trigger language plpgsql as $$
declare lock_month date; col text := tg_argv[0]; d_new date; d_old date;
begin
  if bm_role() = 'admin' then return new; end if;
  select nullif(data ->> 'lockedThrough', '')::date into lock_month from org_settings where id = 'org';
  if lock_month is null then return new; end if;
  d_new := (to_jsonb(new) ->> col)::date;
  if tg_op = 'UPDATE' then d_old := (to_jsonb(old) ->> col)::date; end if;
  if (d_new is not null and d_new < (lock_month + interval '1 month')::date)
     or (d_old is not null and d_old < (lock_month + interval '1 month')::date) then
    raise exception 'BM_LOCKED: period locked through %', to_char(lock_month, 'YYYY-MM') using errcode = 'P0001';
  end if;
  return new;
end $$;

-- 3. server stamp: revision, server time, author (clients cannot forge these)
create or replace function bm_stamp() returns trigger language plpgsql as $$
begin
  new.rev := case when tg_op = 'UPDATE' then old.rev + 1 else 1 end;
  new.server_updated_at := clock_timestamp();
  new.updated_by := auth.uid();
  return new;
end $$;
`);

for (const def of LOGS) {
  const t = q(def.key);
  sql(`
drop trigger if exists bm_10_site on ${t};
create trigger bm_10_site before insert or update on ${t} for each row execute function bm_set_site('${SITE_SCOPE[def.key]}');
drop trigger if exists bm_20_lock on ${t};
create trigger bm_20_lock before insert or update on ${t} for each row execute function bm_check_lock('${def.dateField}');
drop trigger if exists bm_90_stamp on ${t};
create trigger bm_90_stamp before insert or update on ${t} for each row execute function bm_stamp();`);
}
for (const t of ['org_settings', 'kpi_targets'])
  sql(`
drop trigger if exists bm_90_stamp on ${t};
create trigger bm_90_stamp before insert or update on ${t} for each row execute function bm_stamp();`);

// ---------- row-level security ----------
sql(`
-- ---------- row-level security ----------
alter table sites enable row level security;
alter table profiles enable row level security;
alter table site_members enable row level security;
alter table org_settings enable row level security;
alter table kpi_targets enable row level security;
alter table audit enable row level security;

drop policy if exists bm_read on sites;
create policy bm_read on sites for select to authenticated using (bm_role() <> 'none' and bm_role() <> 'pending');
drop policy if exists bm_admin on sites;
create policy bm_admin on sites for all to authenticated using (bm_role() = 'admin') with check (bm_role() = 'admin');

drop policy if exists bm_read on profiles;
create policy bm_read on profiles for select to authenticated using (id = auth.uid() or bm_role() = 'admin');
drop policy if exists bm_admin on profiles;
create policy bm_admin on profiles for update to authenticated using (bm_role() = 'admin') with check (bm_role() = 'admin');

drop policy if exists bm_read on site_members;
create policy bm_read on site_members for select to authenticated using (user_id = auth.uid() or bm_role() = 'admin');
drop policy if exists bm_admin on site_members;
create policy bm_admin on site_members for all to authenticated using (bm_role() = 'admin') with check (bm_role() = 'admin');

drop policy if exists bm_read on org_settings;
create policy bm_read on org_settings for select to authenticated using (bm_role() in ('admin', 'executive', 'pm'));
drop policy if exists bm_write on org_settings;
create policy bm_write on org_settings for insert to authenticated with check (bm_role() = 'admin');
drop policy if exists bm_update on org_settings;
create policy bm_update on org_settings for update to authenticated using (bm_role() = 'admin') with check (bm_role() = 'admin');

drop policy if exists bm_read on kpi_targets;
create policy bm_read on kpi_targets for select to authenticated using (bm_role() in ('admin', 'executive', 'pm'));
drop policy if exists bm_write on kpi_targets;
create policy bm_write on kpi_targets for insert to authenticated with check (bm_role() = 'admin');
drop policy if exists bm_update on kpi_targets;
create policy bm_update on kpi_targets for update to authenticated using (bm_role() = 'admin') with check (bm_role() = 'admin');

drop policy if exists bm_insert on audit;
create policy bm_insert on audit for insert to authenticated with check (user_id = auth.uid() and bm_role() in ('admin', 'executive', 'pm'));
drop policy if exists bm_read on audit;
create policy bm_read on audit for select to authenticated using (bm_role() in ('admin', 'executive') or user_id = auth.uid());
`);

const writeRule: Record<string, string> = {
  self: `bm_role() = 'admin' or (bm_role() = 'pm' and pm = bm_owner() and bm_member(site_id))`,
  project: `bm_role() = 'admin' or bm_owns_project(project)`,
  site: `bm_role() = 'admin' or (bm_role() = 'pm' and bm_member(site_id))`,
  projectOrSite: `bm_role() = 'admin' or (project is not null and bm_owns_project(project)) or (project is null and bm_role() = 'pm' and bm_member(site_id))`,
  global: `bm_role() = 'admin'`,
};

for (const def of LOGS) {
  const t = q(def.key);
  const rule = writeRule[SITE_SCOPE[def.key]];
  sql(`
alter table ${t} enable row level security;
drop policy if exists bm_read on ${t};
create policy bm_read on ${t} for select to authenticated using (bm_can_read(site_id));
drop policy if exists bm_insert on ${t};
create policy bm_insert on ${t} for insert to authenticated with check (${rule});
drop policy if exists bm_update on ${t};
create policy bm_update on ${t} for update to authenticated using (${rule}) with check (${rule});
-- no delete policy: rows are soft-deleted (deleted = true) so the deletion syncs and stays audited`);
}

sql(`
-- ---------- read-only reporting role (Power BI / Excel live connection) ----------
-- Members of bm_reporting read every row of every log and write nothing. To use it:
--   create role powerbi login password '<strong password>' in role bm_reporting;
do $$ begin
  if not exists (select from pg_roles where rolname = 'bm_reporting') then create role bm_reporting nologin; end if;
end $$;
grant usage on schema public to bm_reporting;
grant select on sites, kpi_targets, org_settings to bm_reporting;`);
for (const t of ['sites', 'kpi_targets', 'org_settings', ...LOGS.map((l) => l.key)]) {
  sql(`grant select on ${q(t)} to bm_reporting;
drop policy if exists bm_reporting_read on ${q(t)};
create policy bm_reporting_read on ${q(t)} for select to bm_reporting using (true);`);
}

const tables = [...LOGS.map((l) => l.key), 'org_settings', 'kpi_targets'];
sql(`
-- ---------- sync: push with optimistic concurrency ----------
-- p_rows: [{ id, base_rev, deleted, updated_at, ...fields }]
-- returns one result per row: ok (new rev) | conflict (server row) | denied (reason)
create or replace function bm_push(p_table text, p_rows jsonb) returns jsonb language plpgsql security invoker set search_path = public as $$
declare
  r jsonb; res jsonb := '[]'::jsonb; cur_rev bigint; cols text; new_rev bigint; new_ts timestamptz; n int; srv jsonb;
begin
  if p_table <> all (array[${tables.map((t) => `'${t}'`).join(', ')}]) then
    raise exception 'BM_BAD_TABLE: %', p_table;
  end if;
  select string_agg(quote_ident(column_name), ', ' order by ordinal_position) into cols
    from information_schema.columns
   where table_schema = 'public' and table_name = p_table
     and column_name not in ('id', 'rev', 'site_id', 'updated_by', 'server_updated_at');

  for r in select * from jsonb_array_elements(p_rows) loop
    r := jsonb_build_object('deleted', false) || r;
    begin
      execute format('select rev from %I where id = $1', p_table) into cur_rev using r ->> 'id';
      if cur_rev is not null and cur_rev <> coalesce((r ->> 'base_rev')::bigint, 0) then
        execute format('select to_jsonb(t) from %I t where id = $1', p_table) into srv using r ->> 'id';
        res := res || jsonb_build_object('id', r ->> 'id', 'status', 'conflict', 'server', srv);
        continue;
      end if;
      if cur_rev is null then
        execute format('insert into %I (id, %s) select $2, %s from jsonb_populate_record(null::%I, $1) returning rev, server_updated_at',
                       p_table, cols, cols, p_table) into new_rev, new_ts using r, r ->> 'id';
      else
        execute format('update %I t set (%s) = (select %s from jsonb_populate_record(null::%I, $1)) where t.id = $2 returning rev, server_updated_at',
                       p_table, cols, cols, p_table) into new_rev, new_ts using r, r ->> 'id';
        get diagnostics n = row_count;
        if n = 0 then raise exception 'BM_DENIED: not allowed to change this record' using errcode = '42501'; end if;
      end if;
      res := res || jsonb_build_object('id', r ->> 'id', 'status', 'ok', 'rev', new_rev, 'server_updated_at', new_ts);
    exception when others then
      res := res || jsonb_build_object('id', r ->> 'id', 'status', 'denied', 'reason', sqlerrm);
    end;
  end loop;
  return res;
end $$;

-- ---------- grants (Supabase: anon = not signed in, authenticated = signed in) ----------
revoke all on all tables in schema public from anon;
grant select, insert, update on all tables in schema public to authenticated;
grant delete on site_members to authenticated; -- admins re-assign sites (policy bm_admin)
grant execute on function bm_push(text, jsonb) to authenticated;
revoke execute on function bm_push(text, jsonb) from anon;
`);

process.stdout.write(out.join('\n'));
